#!/bin/sh
# Указывает операционной системе использовать Bourne shell (sh) для исполнения этого скрипта

VOLUME_DIR="/data"
# Создает переменную с путем к рабочей директории, где будут создаваться файлы

LOCK_FILE="$VOLUME_DIR/lockfile"
# Создает переменную с путем к файлу блокировки для синхронизации процессов

# Функция обработки исключений
# Комментарий, поясняющий назначение функции ниже

exceptions(){
# Объявляет функцию exceptions для вывода ошибок и аварийного завершения

  echo "Ошибка: $1" >&2
  # Выводит переданный текст ошибки в стандартный поток ошибок (stderr)

  exit "${2:-1}"
  # Завершает скрипт с кодом из второго аргумента, либо с кодом 1 по умолчанию

}
# Конец функции exceptions

cleanUp() {
# Объявляет функцию cleanUp для очистки мусора при выходе из скрипта

  if [ -n "$current_file" ]; then
  # Проверяет, остался ли не удаленный файл (если переменная current_file не пуста)

    rm -f "$current_file"
    # Принудительно удаляет этот файл, игнорируя отсутствие файла или ошибки

    echo "Удален файл $current_file."
    # Выводит сообщение в консоль об успешном удалении файла при очистке

  fi
  # Конец проверки условия if

  exit 0
  # Завершает работу скрипта с кодом 0 (успешное выполнение)

}
# Конец функции cleanUp

# Проверка на существование каталога
# Комментарий, поясняющий проверку директории

[ -d "$VOLUME_DIR" ] || exceptions "каталог $VOLUME_DIR не существует"
# Если директория /data не существует, вызывает функцию exceptions с ошибкой

# Уникальный ID контейнера
# Комментарий, поясняющий генерацию UUID

id_container=$(cat /proc/sys/kernel/random/uuid)
# Генерирует случайный UUID и сохраняет его в переменную id_container

[ -n "$id_container" ] || exceptions "не удалось получить UUID контейнера"
# Проверяет, что UUID сгенерировался; если строка пустая — вызывает ошибку

counter_files=0
# Инициализирует счетчик созданных за сессию файлов со значения 0

current_file=""
# Инициализирует переменную для отслеживания текущего файла пустой строкой

trap cleanUp EXIT HUP INT TERM
# Перехватывает сигналы завершения (выход, прерывание Ctrl+C и т.д.) и запускает cleanUp

echo "Контейнер $id_container запущен."
# Выводит сообщение о старте контейнера вместе с его уникальным UUID

while true; do
# Начинает бесконечный цикл выполнения основной логики скрипта

  # Счётчик созданных файлов
  # Комментарий, поясняющий инкремент счетчика

  counter_files=$((counter_files + 1))
  # Увеличивает счетчик созданных файлов на 1 при каждой итерации

  # Открываем lock_file как дескриптор 8
  # Комментарий, поясняющий работу с файловым дескриптором

  exec 8>"$LOCK_FILE" || exceptions "Не удается открыть файл $LOCK_FILE"
  # Открывает файл блокировки на запись под номером дескриптора 8 или выдает ошибку

  flock -x 8
  # Ставит эксклюзивную блокировку на дескриптор 8, приостанавливая другие процессы

  i=1
  # Задает стартовое число 1 для поиска свободного имени файла (001, 002...)

  while true; do
  # Начинает внутренний бесконечный цикл для поиска свободного имени файла

    NUM=$(printf '%03d' "$i")
    # Форматирует число i в строку из 3 цифр с ведущими нулями (например, "001")

    FILE_PATH="$VOLUME_DIR/$NUM"
    # Формирует полный путь к проверяемому файлу (например, "/data/001")

    if [ ! -e "$FILE_PATH" ]; then
    # Проверяет, если файла с таким путем еще НЕ существует

      echo "$id_container $counter_files" > "$FILE_PATH"
      # Создает файл и записывает в него UUID контейнера и номер итерации

      current_file="$FILE_PATH"
      # Сохраняет путь к созданному файлу в переменную для функции cleanUp

      break
      # Прерывает внутренний цикл, так как файл успешно создан

    fi
    # Конец проверки условия if

    i=$((i + 1))
    # Увеличивает i на 1, чтобы на следующем шаге проверить следующее имя файла

  done
  # Конец внутреннего цикла поиска имени

  # Закрываем дескриптор и снимаем блокировку
  # Комментарий, поясняющий освобождение файла блокировки

  exec 8>&-
  # Закрывает файловый дескриптор 8, что автоматически снимает блокировку flock

  echo "Создан: $current_file"
  # Выводит в консоль информацию о том, какой файл был создан

  # Задержка между созданием и удалением
  # Комментарий, поясняющий паузу перед удалением

  sleep 1
  # Приостанавливает работу скрипта на 1 секунду, пока файл существует

  rm -f "$current_file"
  # Удаляет только что созданный файл

  echo "Удалён: $current_file"
  # Выводит в консоль информацию об удалении файла

  current_file=""
  # Сбрасывает переменную пути, так как файл успешно удален в штатном режиме

  # Задержка между удалением и следующим созданием
  # Комментарий, поясняющий паузу перед следующей итерацией

  sleep 1
  # Приостанавливает работу скрипта на 1 секунду перед началом нового цикла

done
# Конец основного бесконечного цикла скрипта
